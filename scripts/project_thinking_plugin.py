#!/usr/bin/env python3
"""Generate the independently copyable Thinking plugin from canonical skills."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ("blindspot", "research", "goalify")
VERSION = "0.1.1"
README = """# Thinking

Three independent skills: Blindspot researches missing expertise and applies it;
Research verifies evidence; Goalify clarifies intent. Start with the skill your task
needs. There is no mandatory chain. Blindspot remains experimental; packaging does
not establish improved outcomes. Product Bet Shaping and Plan are not included.

This directory is generated by `scripts/project_thinking_plugin.py` from canonical
`skills/thinking/` sources in alex-furrier/skills. Edit the canonical files and
regenerate; do not maintain another editable source here. The copied directory is
self-contained: skill instructions, references, licenses and provenance travel with it.

Try a copied plugin without installing it:

```bash
claude --plugin-dir /absolute/path/to/thinking
```

Select Blindspot, Research or Goalify in that session. With Pi, load one skill using
`pi --skill /absolute/path/to/thinking/skills/research`. Other hosts can import each
SKILL.md and its adjacent resources through their supported skill import mechanism.
The plugin selects no model, provider, account, private source or default profile.
Do not install tools or persist findings without the task's authorization.
"""


def encoded(value: object) -> bytes:
    return (json.dumps(value, indent=2) + "\n").encode()


def build(root: Path) -> dict[str, bytes]:
    source = root / "skills/thinking"
    if source.is_symlink() or any((source / name).is_symlink() for name in SKILLS):
        raise ValueError("Refusing symlinked canonical Thinking root")
    actual = {path.name for path in source.iterdir() if path.is_dir()}
    if actual != set(SKILLS):
        raise ValueError(
            f"Thinking must contain exactly {SKILLS}; found {sorted(actual)}"
        )
    files = {
        ".claude-plugin/plugin.json": encoded(
            {
                "name": "thinking",
                "version": VERSION,
                "description": "Clarify goals, verify evidence and apply missing expertise",
                "skills": [f"./skills/{name}" for name in SKILLS],
            }
        ),
        "README.md": README.encode(),
        "LICENSE": (root / "LICENSE").read_bytes(),
        "provenance.json": encoded(
            {
                "schema": 1,
                "decision": "Generated projection of canonical skills/thinking in alex-furrier/skills. Per-skill provenance records Dots input revisions and hashes; current skill ownership is this catalog. No CLI, private corpus, historical eval or Product Bet Shaping is bundled.",
                "entries": [
                    {
                        "path_prefix": "skills/",
                        "origin": "exact projection of canonical Thinking skills with their licenses and source provenance",
                        "license": "MIT",
                    },
                    {
                        "path_prefix": ".claude-plugin/",
                        "origin": "generated plugin metadata",
                        "license": "MIT",
                    },
                    {
                        "path": "README.md",
                        "origin": "generated usage guide",
                        "license": "MIT",
                    },
                    {
                        "path": "LICENSE",
                        "origin": "catalog MIT license",
                        "license": "MIT",
                    },
                    {
                        "path": "provenance.json",
                        "origin": "generated plugin-scoped inventory",
                        "license": "MIT",
                    },
                ],
            }
        ),
    }
    for name in SKILLS:
        for path in sorted((source / name).rglob("*")):
            if path.is_symlink():
                raise ValueError(f"Symlink in canonical skill: {path}")
            if path.is_file():
                files[f"skills/{path.relative_to(source).as_posix()}"] = (
                    path.read_bytes()
                )
    return files


def check(files: dict[str, bytes], destination: Path) -> bool:
    if destination.is_symlink():
        return False
    actual = {}
    for path in destination.rglob("*"):
        if path.is_symlink():
            return False
        if path.is_file():
            actual[path.relative_to(destination).as_posix()] = path.read_bytes()
    return actual == files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = build(ROOT)
    destination = ROOT / "plugins/thinking"
    if args.check:
        if not check(files, destination):
            print(
                "Thinking plugin projection is stale; run python scripts/project_thinking_plugin.py"
            )
            return 1
        print("Thinking plugin projection is current")
        return 0
    if destination.is_symlink():
        raise ValueError("Refusing symlinked generated plugin root")
    # Only the named generated plugin is reconciled; canonical sources are never edited.
    for path in destination.rglob("*"):
        if path.is_symlink():
            raise ValueError(f"Refusing symlink in generated plugin: {path}")
        if path.is_file() and path.relative_to(destination).as_posix() not in files:
            path.unlink()
    for relative, data in files.items():
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
